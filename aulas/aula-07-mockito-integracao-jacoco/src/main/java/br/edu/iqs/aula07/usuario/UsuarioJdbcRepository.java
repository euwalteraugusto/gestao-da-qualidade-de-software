package br.edu.iqs.aula07.usuario;

import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.ArrayList;
import java.util.List;
import java.util.Objects;

import javax.sql.DataSource;

/**
 * Implementacao JDBC (SQL padrao, funciona em PostgreSQL 10+ e H2 em modo PostgreSQL).
 * Alvo do teste de integracao com Testcontainers.
 */
public class UsuarioJdbcRepository implements UsuarioRepository {

    private final DataSource dataSource;

    public UsuarioJdbcRepository(DataSource dataSource) {
        this.dataSource = Objects.requireNonNull(dataSource, "dataSource");
    }

    /** Cria a tabela se ainda nao existir (nome unico, para poder provocar falha no rollback). */
    public void criarTabelaSeNecessario() {
        try (Connection conexao = dataSource.getConnection();
             Statement st = conexao.createStatement()) {
            st.execute("CREATE TABLE IF NOT EXISTS usuarios ("
                    + "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                    + "nome VARCHAR(100) NOT NULL UNIQUE)");
        } catch (SQLException e) {
            throw new PersistenciaException("Falha ao criar a tabela de usuários", e);
        }
    }

    @Override
    public void salvar(Usuario usuario) {
        try (Connection conexao = dataSource.getConnection()) {
            inserir(conexao, usuario);
        } catch (SQLException e) {
            throw new PersistenciaException("Falha ao salvar o usuário " + usuario.getNome(), e);
        }
    }

    @Override
    public void salvarTodos(List<Usuario> usuarios) {
        List<Usuario> inseridos = new ArrayList<>();
        try (Connection conexao = dataSource.getConnection()) {
            conexao.setAutoCommit(false);
            try {
                for (Usuario usuario : usuarios) {
                    inserir(conexao, usuario);
                    inseridos.add(usuario);
                }
                conexao.commit();
            } catch (SQLException | RuntimeException e) {
                conexao.rollback();
                // O banco desfez tudo; os objetos em memoria nao devem fingir que tem id.
                inseridos.forEach(u -> u.setId(null));
                throw e;
            }
        } catch (SQLException e) {
            throw new PersistenciaException("Falha ao salvar usuários em lote (rollback executado)", e);
        }
    }

    @Override
    public Usuario buscarPorId(Long id) {
        try (Connection conexao = dataSource.getConnection();
             PreparedStatement ps = conexao.prepareStatement("SELECT id, nome FROM usuarios WHERE id = ?")) {
            ps.setLong(1, id);
            try (ResultSet rs = ps.executeQuery()) {
                return rs.next() ? mapear(rs) : null;
            }
        } catch (SQLException e) {
            throw new PersistenciaException("Falha ao buscar o usuário " + id, e);
        }
    }

    @Override
    public List<Usuario> buscarTodos() {
        List<Usuario> resultado = new ArrayList<>();
        try (Connection conexao = dataSource.getConnection();
             Statement st = conexao.createStatement();
             ResultSet rs = st.executeQuery("SELECT id, nome FROM usuarios ORDER BY id")) {
            while (rs.next()) {
                resultado.add(mapear(rs));
            }
            return resultado;
        } catch (SQLException e) {
            throw new PersistenciaException("Falha ao listar usuários", e);
        }
    }

    private static void inserir(Connection conexao, Usuario usuario) throws SQLException {
        try (PreparedStatement ps = conexao.prepareStatement(
                "INSERT INTO usuarios (nome) VALUES (?)", new String[] {"id"})) {
            ps.setString(1, usuario.getNome());
            ps.executeUpdate();
            try (ResultSet chaves = ps.getGeneratedKeys()) {
                if (chaves.next()) {
                    usuario.setId(chaves.getLong(1));
                }
            }
        }
    }

    private static Usuario mapear(ResultSet rs) throws SQLException {
        Usuario usuario = new Usuario(rs.getString("nome"));
        usuario.setId(rs.getLong("id"));
        return usuario;
    }
}
